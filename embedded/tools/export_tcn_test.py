# -*- coding: utf-8 -*-
"""Write include/tcn_test_gen.h: a few real 167-sample windows (three bandpass channels
at 110 Hz, from reference/tcn_ref_<recording>.npz written by tcn_streaming_check.py)
together with the PyTorch head outputs, for the on-device TCN self-test.

    python export_tcn_test.py [--recording Ramp_60s] [--positions 166,1000,5000,20000]
"""
import os
import argparse
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.abspath(os.path.join(HERE, '..'))
WL = 167


def carr(name, arr, per_line=6):
    a = np.asarray(arr, dtype=np.float32).ravel()
    out = ['static const float %s[%d] = {' % (name, a.size)]
    for i in range(0, a.size, per_line):
        out.append('  ' + ', '.join('%.9ef' % v for v in a[i:i + per_line]) + ',')
    out.append('};')
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--recording', default='Ramp_60s')
    ap.add_argument('--positions', default='166,1000,5000,20000,30000')
    args = ap.parse_args()
    z = np.load(os.path.join(PROJ, 'reference', 'tcn_ref_%s.npz' % args.recording))
    x = z['x_ds']                      # (n, 3) float32 stream
    pos = [int(p) for p in args.positions.split(',')]
    wins, outs = [], []
    for t in pos:
        w = np.zeros((WL, 3), np.float32)
        lo = max(0, t - WL + 1)
        w[WL - (t + 1 - lo):] = x[lo:t + 1]
        wins.append(w)
        outs.append(np.concatenate([z['win_pa'][t], z['win_pd'][t], [z['win_pc'][t]]]))
    L = ['/* AUTO-GENERATED by tools/export_tcn_test.py -- do not edit.',
         ' * %d windows of %s at 110 Hz positions %s; expected = PyTorch [pa0 pa1 pd0 pd1 pc]. */'
         % (len(pos), args.recording, pos),
         '#ifndef TCN_TEST_GEN_H', '#define TCN_TEST_GEN_H',
         '#define TCN_TEST_N %d' % len(pos),
         '/* [TCN_TEST_N][167][3], oldest sample first */',
         carr('TCN_TEST_WIN', np.stack(wins)),
         '/* [TCN_TEST_N][5] */',
         carr('TCN_TEST_EXPECT', np.stack(outs)),
         '#endif /* TCN_TEST_GEN_H */', '']
    path = os.path.join(PROJ, 'include', 'tcn_test_gen.h')
    with open(path, 'w') as f:
        f.write('\n'.join(L))
    print('wrote', path, 'positions', pos)
    for t, o in zip(pos, outs):
        print('  t=%6d  expect pa=[%.4f %.4f] pd=[%.4f %.4f] pc=%.4f' % (t, *o))


if __name__ == '__main__':
    main()
