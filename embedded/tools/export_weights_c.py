"""Export the trained AO+TCN model to a C header for microcontroller deployment.

Performs three transforms that make the network cheap enough to stream on an MCU,
all of them exactly lossless:

  1. BatchNorm folding. At inference BN is an affine map, so it collapses into the
     preceding conv:  W' = W * g/sqrt(var+eps),  b' = (b-mean)*g/sqrt(var+eps) + beta.
     Removes 7 BN layers and their running buffers from the runtime entirely.

  2. Dead-tap pruning. Each conv left-pads its own input with (k-1)*d zeros, so for a
     WL-sample window any tap reaching further back than WL-1 reads a structural zero
     at every output position. Those weights never received gradient and sit at
     denormal magnitudes (~6e-40) in the trained checkpoint. Dropping them is exact,
     not approximate.

  3. Emission as variable-tap conv layers, so the pruned taps cost neither flash nor
     multiply-accumulates at runtime.

Usage (from embedded/):

    python tools/export_weights_c.py ../weights/tcn_hybrid_7L48f.pt include/tcn_weights_gen.h

Writes the header and <header>_footprint.json next to it.
"""
import os, sys, json
os.environ['KMP_DUPLICATE_LIB_OK'] = 'TRUE'
import numpy as np
import torch

if len(sys.argv) != 3:
    sys.exit('usage: python export_weights_c.py <checkpoint.pt> <out.h>')
CKPT = sys.argv[1]
OUT_H = sys.argv[2]
OUT_J = os.path.splitext(OUT_H)[0] + '_footprint.json'

DIL = (1, 2, 4, 8, 16, 64, 128)
K = 5
NF = 48
NCH = 3
WL = 167                 # training/eval window at the 110 Hz downsampled rate
DS_FACTOR = 3
FS = 330.0
BN_EPS = 1e-5            # nn.BatchNorm1d default
GN_EPS = 1e-5            # nn.GroupNorm default
DEAD_TAP_THRESH = 1e-20  # trained dead taps sit at ~6e-40; live taps at ~1e-1


def fold_bn(w, b, gamma, beta, mean, var, eps=BN_EPS):
    """Fold BatchNorm1d into the preceding conv. Exact at inference."""
    scale = gamma / np.sqrt(var + eps)
    return w * scale[:, None, None], (b - mean) * scale + beta


def carr(name, arr, per_line=8):
    """Emit a flat const float array."""
    a = np.asarray(arr, dtype=np.float32).ravel()
    out = [f"static const float {name}[{a.size}] = {{"]
    for i in range(0, a.size, per_line):
        out.append("  " + ", ".join(f"{v:.8e}f" for v in a[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)


def iarr(name, arr):
    a = np.asarray(arr, dtype=np.int32).ravel()
    return (f"static const int {name}[{a.size}] = {{ "
            + ", ".join(str(int(v)) for v in a) + " };")


def main():
    sd = torch.load(CKPT, map_location='cpu', weights_only=True)
    print(f"loaded {os.path.basename(CKPT)}")

    trainable = sum(v.numel() for k, v in sd.items()
                    if 'running' not in k and 'num_batches' not in k)
    print(f"trainable params in checkpoint: {trainable}\n")

    lines = [
        "/* AUTO-GENERATED by export_weights_c.py -- do not edit by hand.",
        " *",
        f" * Source checkpoint : {os.path.basename(CKPT)} (3-channel multi-head AO+TCN)",
        " * BatchNorm folded into conv weights; zero-fed taps pruned.",
        " */",
        "#ifndef TCN_WEIGHTS_H",
        "#define TCN_WEIGHTS_H",
        "",
        f"#define TCN_N_LAYERS   {len(DIL)}",
        f"#define TCN_N_CH       {NCH}",
        f"#define TCN_NF         {NF}",
        f"#define TCN_K          {K}",
        f"#define TCN_WL         {WL}",
        f"#define TCN_DS_FACTOR  {DS_FACTOR}",
        f"#define TCN_FS_HZ      {FS:.1f}f",
        "",
    ]

    # --- input GroupNorm(1, 3) affine ------------------------------------------
    lines += [
        "/* GroupNorm(1,3): statistics are pooled over all channels AND the whole",
        " * window, then this per-channel affine is applied. */",
        carr("TCN_GN_W", sd['norm.weight'].numpy()),
        carr("TCN_GN_B", sd['norm.bias'].numpy()),
        f"#define TCN_GN_EPS {GN_EPS:.8e}f",
        "",
    ]

    tot_live_mac = 0
    tot_live_par = 0
    tot_dead_par = 0
    layer_meta = []

    for li, d in enumerate(DIL):
        w = sd[f'convs.{li}.c.weight'].numpy().astype(np.float64)
        b = sd[f'convs.{li}.c.bias'].numpy().astype(np.float64)
        w, b = fold_bn(w, b,
                       sd[f'bns.{li}.weight'].numpy().astype(np.float64),
                       sd[f'bns.{li}.bias'].numpy().astype(np.float64),
                       sd[f'bns.{li}.running_mean'].numpy().astype(np.float64),
                       sd[f'bns.{li}.running_var'].numpy().astype(np.float64))

        # tap j reads offset -(K-1-j)*d relative to the output sample
        offsets = [-(K - 1 - j) * d for j in range(K)]
        live = [j for j in range(K) if np.abs(w[:, :, j]).max() > DEAD_TAP_THRESH]
        dead = [j for j in range(K) if j not in live]

        # cross-check: a tap is dead exactly when it reaches outside the window
        expect_dead = [j for j in range(K) if abs(offsets[j]) > WL - 1]
        if dead != expect_dead:
            print(f"  !! L{li+1}: pruned taps {dead} != structurally-zero taps "
                  f"{expect_dead}; refusing to guess")
            sys.exit(1)

        n_in = NCH if li == 0 else NF
        wl_ = w[:, :, live].transpose(2, 0, 1)                # [n_live, out, in]: one contiguous [out][in] block per tap (RAM-stageable in 9 kB pieces)
        live_off = [offsets[j] for j in live]
        tot_live_mac += NF * n_in * len(live)
        tot_live_par += wl_.size + b.size
        tot_dead_par += NF * n_in * len(dead)

        lines += [
            f"/* layer {li+1}: dilation {d}, taps {live_off} "
            f"({len(dead)} pruned) */",
            carr(f"TCN_W{li}", wl_),
            carr(f"TCN_B{li}", b),
            iarr(f"TCN_OFF{li}", live_off),
            "",
        ]
        layer_meta.append({'n_in': n_in, 'n_out': NF, 'n_taps': len(live),
                           'dilation': d, 'offsets': live_off,
                           'pruned': [offsets[j] for j in dead]})
        print(f"  L{li+1} d={d:3d}: live taps {live_off}"
              + (f"   pruned {[offsets[j] for j in dead]}" if dead else ""))

    # --- heads (ha = absolute phase, hd = AO delta, hc = confidence) -----------
    # head names differ between checkpoints: (ha, hd, hc) or (head_abs, head_add, head_conf)
    alias = {'ha': 'head_abs', 'hd': 'head_add', 'hc': 'head_conf'}
    def hk(src, what):
        return f'{src}.{what}' if f'{src}.{what}' in sd else f'{alias[src]}.{what}'
    for src, dst in (('ha', 'HA'), ('hd', 'HD'), ('hc', 'HC')):
        lines += [carr(f"TCN_{dst}_W", sd[hk(src, 'weight')].numpy()),
                  carr(f"TCN_{dst}_B", sd[hk(src, 'bias')].numpy()), ""]
    tot_live_par += sum(sd[hk(s, 'weight')].numel() + sd[hk(s, 'bias')].numel()
                        for s in ('ha', 'hd', 'hc'))
    tot_live_par += sd['norm.weight'].numel() + sd['norm.bias'].numel()
    head_mac = NF * 2 * 2 + NF

    # --- layer table -----------------------------------------------------------
    lines += ["typedef struct {",
              "  int n_in, n_out, n_taps;",
              "  const int   *off;   /* negative sample offsets, length n_taps */",
              "  const float *w;     /* [n_taps][n_out][n_in] */",
              "  const float *b;     /* [n_out] */",
              "} tcn_layer_t;",
              "",
              "static const tcn_layer_t TCN_LAYERS[TCN_N_LAYERS] = {"]
    for li, m in enumerate(layer_meta):
        lines.append(f"  {{ {m['n_in']}, {m['n_out']}, {m['n_taps']}, "
                     f"TCN_OFF{li}, TCN_W{li}, TCN_B{li} }},")
    lines += ["};", ""]

    # --- ring-buffer depth per layer ------------------------------------------
    # layer li needs history back to its furthest live tap, capped at the window
    depths = []
    for li, m in enumerate(layer_meta):
        need = max(abs(o) for o in m['offsets']) + 1
        depths.append(min(need, WL))
    lines += ["/* per-layer input ring-buffer depth (columns) */",
              iarr("TCN_DEPTH", depths), ""]

    act_floats = sum(dep * m['n_in'] for dep, m in zip(depths, layer_meta))
    lines += [f"#define TCN_ACT_FLOATS {act_floats}", "",
              "#endif /* TCN_WEIGHTS_H */", ""]

    path = OUT_H
    with open(path, 'w') as f:
        f.write("\n".join(lines))

    stats = {
        'params_trained': int(trainable),
        'params_deployed': int(tot_live_par),
        'params_pruned': int(tot_dead_par),
        'pruned_frac': round(tot_dead_par / trainable, 4),
        'mac_per_sample_streaming': int(tot_live_mac + head_mac),
        'mac_per_sample_unpruned': int(NF * NCH * K + 6 * NF * NF * K + head_mac),
        'activation_floats': int(act_floats),
        'activation_kb_fp32': round(act_floats * 4 / 1024, 1),
        'weights_kb_fp32': round(tot_live_par * 4 / 1024, 1),
        'layer_depths': depths,
        'window_samples': WL,
        'window_s': round(WL / (FS / DS_FACTOR), 3),
        'nominal_rf_samples': sum((K - 1) * d for d in DIL) + 1,
    }
    with open(OUT_J, 'w') as f:
        json.dump(stats, f, indent=2)

    print(f"\nparams   trained {stats['params_trained']}  -> deployed "
          f"{stats['params_deployed']}  (pruned {stats['params_pruned']}, "
          f"{100*stats['pruned_frac']:.1f}%)")
    print(f"MAC/sample  {stats['mac_per_sample_unpruned']} -> "
          f"{stats['mac_per_sample_streaming']}")
    print(f"weights     {stats['weights_kb_fp32']} kB fp32 (flash)")
    print(f"activations {stats['activation_kb_fp32']} kB fp32 (SRAM), "
          f"depths {depths}")
    print(f"\nwrote {path}")


if __name__ == '__main__':
    main()
